/**
 * 주석을 뺀다. 정규식 기반이다 — AST를 파싱하지 않는다.
 * 순서가 중요하다: 줄 주석(`//`)을 먼저 지우고 블록 주석(`/*`~`*\/`)을 나중에 지운다. 반대로 하면, 줄 주석 안의 텍스트에
 * 우연히 `/*`가 들어 있을 때(예: 경로 표기 `Contracts/*.cs`) 블록 주석 정규식이 그 지점부터 열려 뒤에 나오는 진짜
 * 블록 주석의 닫는 `*\/`에서야 멈춰, 그 사이의 실제 코드를 함께 지워 버린다. 줄 주석을 먼저 지우면 그 `/*`가
 * 블록 주석 정규식에 도달하기 전에 사라진다.
 * 한계: 문자열 리터럴 안의 `/*`는 여전히 블록 주석 시작으로 본다(정규식이라 문자열과 코드를 구분하지 못한다) —
 * 이 함수를 쓰는 검사는 export·import 줄 수가 원본과 제거본에서 같은지 스스로 확인해 그 경우를 잡는다.
 * 줄 주석 규칙: 따옴표(`'`·`"`·백틱)·콜론(`:`)·백슬래시(`\`) 바로 뒤의 `//`는 지우지 않는다(URL·문자열·정규식 이스케이프 보존).
 */
export function stripComments(text: string): string {
  const withoutLineComments = text.replace(/(^|[^:'"`\\])\/\/.*$/gm, '$1')
  return withoutLineComments.replace(/\/\*[\s\S]*?\*\//g, '')
}
